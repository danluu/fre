require_canonical_lock_without_compiler_backend() {
    local lock=$1
    local label=$2
    fre_c5_require_text_bounds "$lock" 1048576 8192 16384 "$label"
    awk -v label="$label" '
        NR == 1 && $0 != "# This file is automatically @generated by Cargo." {
            bad = 1
        }
        NR == 2 && $0 != "# It is not intended for manual editing." {
            bad = 1
        }
        NR == 3 && $0 != "version = 4" { bad = 1 }
        NR == 4 && $0 != "" { bad = 1 }
        /^\[\[package\]\]$/ {
            if (in_package && package_names != 1) bad = 1
            in_package = 1
            package_names = 0
            packages++
            next
        }
        /^[[:space:]]*name[[:space:]]*=/ {
            if (!in_package ||
                $0 !~ /^name = "[A-Za-z0-9][A-Za-z0-9_-]*"$/) {
                bad = 1
                next
            }
            name = $0
            sub(/^name = "/, "", name)
            sub(/"$/, "", name)
            package_names++
            normalized = tolower(name)
            if (normalized ~ /(llvm|inkwell|cranelift)/) {
                print label ": forbidden compiler package: " name > "/dev/stderr"
                bad = 1
            }
            next
        }
        /^\[\[/ && $0 != "[[package]]" { bad = 1 }
        index($0, "\r") != 0 { bad = 1 }
        END {
            if (NR < 5 || packages == 0 ||
                (in_package && package_names != 1)) {
                bad = 1
            }
            exit bad ? 1 : 0
        }
    ' "$lock" ||
        fre_c5_die "$label is not a canonical Cargo v4 lock without a compiler backend"
}

require_exact_toml_section() {
    local manifest=$1
    local section=$2
    local expected=$3
    local actual=$4
    local label=$5
    fre_c5_require_text_bounds "$manifest" 65536 2048 2048 "$label"
    awk -v section="$section" '
        /^\[/ {
            active = 0
            if ($0 == section) {
                sections++
                active = 1
            }
        }
        active { print }
        END { exit sections == 1 ? 0 : 1 }
    ' "$manifest" > "$actual" ||
        fre_c5_die "$label does not contain one exact $section section"
    cmp -s "$expected" "$actual" ||
        fre_c5_die "$label differs from the closed $section contract"
}

require_literal_occurrences() {
    local file=$1
    local literal=$2
    local expected=$3
    local label=$4
    awk -v literal="$literal" -v expected="$expected" '
        {
            remaining = $0
            while ((position = index(remaining, literal)) != 0) {
                occurrences++
                remaining = substr(remaining, position + length(literal))
            }
        }
        END { exit occurrences == expected ? 0 : 1 }
    ' "$file" ||
        fre_c5_die "$label does not contain exactly $expected occurrences of $literal"
}

require_recorded_dependency_tree_grammar() {
    local report=$1
    awk -F '	' '
        $0 == "TREE	benchmark" {
            if (++headers != 1) bad = 1
            section = "benchmark"
            next
        }
        $0 == "TREE	custom-aot-compiler" {
            if (++headers != 2) bad = 1
            section = "compiler"
            next
        }
        $0 == "TREE	workspace-runtime-features" {
            if (++headers != 3) bad = 1
            section = "workspace"
            next
        }
        $0 == "TREE	qualification-runtime-features" {
            if (++headers != 4) bad = 1
            section = "qualification"
            next
        }
        $0 == "TREE	qualification-runtime-reverse" {
            if (++headers != 5) bad = 1
            section = "reverse"
            next
        }
        /^TREE	/ { bad = 1; next }
        section == "benchmark" || section == "compiler" {
            if (NF != 1 ||
                $1 !~ /^[A-Za-z0-9][A-Za-z0-9_-]* v[0-9]/ ||
                $1 ~ /[^A-Za-z0-9._+*() \/-]/) {
                bad = 1
            }
            if (section == "benchmark") benchmark_lines++
            else compiler_lines++
            next
        }
        section == "workspace" ||
        section == "qualification" ||
        section == "reverse" {
            if (NF != 2 ||
                $1 !~ /^[A-Za-z0-9][A-Za-z0-9_-]* v[0-9]/ ||
                $1 ~ /[^A-Za-z0-9._+*() \/-]/ ||
                $2 ~ /[^A-Za-z0-9,_-]/) {
                bad = 1
            }
            next
        }
        { bad = 1 }
        END {
            if (headers != 5 || benchmark_lines == 0 ||
                compiler_lines == 0) bad = 1
            exit bad ? 1 : 0
        }
    ' "$report" ||
        fre_c5_die "recorded dependency report has the wrong closed grammar"
}


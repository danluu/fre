#[derive(Debug)]
struct Config {
    compile_iterations: u32,
    search_iterations: u64,
    haystack_bytes: usize,
    target: Target,
    target_name: &'static str,
    emit_native: Option<PathBuf>,
    native_enabled: bool,
    native_run: bool,
}

#[derive(Debug)]
struct PartialConfig {
    compile_iterations: Option<u32>,
    search_iterations: Option<u64>,
    haystack_bytes: Option<usize>,
    target: Option<(Target, &'static str)>,
    features: Option<FeatureSet>,
    emit_native: Option<PathBuf>,
    full: bool,
    native_enabled: bool,
    native_run: bool,
}

impl Default for PartialConfig {
    fn default() -> Self {
        Self {
            compile_iterations: None,
            search_iterations: None,
            haystack_bytes: None,
            target: None,
            features: None,
            emit_native: None,
            full: false,
            native_enabled: true,
            native_run: true,
        }
    }
}

impl Config {
    fn parse() -> Result<Option<Self>, String> {
        let mut partial = PartialConfig::default();
        let mut arguments = env::args_os().skip(1);
        while let Some(argument) = arguments.next() {
            match argument.to_str() {
                Some("-h" | "--help") => return Ok(None),
                Some("--full") => partial.full = true,
                Some("--no-native") => partial.native_enabled = false,
                Some("--no-native-run") => partial.native_run = false,
                Some("--iterations") => {
                    partial.search_iterations =
                        Some(parse_next::<u64>(&mut arguments, "--iterations")?);
                }
                Some("--compile-iterations") => {
                    partial.compile_iterations =
                        Some(parse_next::<u32>(&mut arguments, "--compile-iterations")?);
                }
                Some("--haystack-bytes") => {
                    partial.haystack_bytes =
                        Some(parse_next::<usize>(&mut arguments, "--haystack-bytes")?);
                }
                Some("--target") => {
                    let value = next_utf8(&mut arguments, "--target")?;
                    partial.target = Some(parse_target(&value)?);
                }
                Some("--features") => {
                    let value = next_utf8(&mut arguments, "--features")?;
                    partial.features = Some(parse_features(&value)?);
                }
                Some("--emit-native") => {
                    partial.emit_native =
                        Some(PathBuf::from(next_os(&mut arguments, "--emit-native")?));
                }
                Some(value) => return Err(format!("unknown argument {value:?}\n\n{}", usage())),
                None => return Err(format!("arguments must be valid UTF-8\n\n{}", usage())),
            }
        }

        if !partial.native_enabled && partial.emit_native.is_some() {
            return Err("--no-native cannot be combined with --emit-native".to_owned());
        }
        let compile_iterations =
            partial
                .compile_iterations
                .unwrap_or(if partial.full { 3 } else { 1 });
        let search_iterations =
            partial
                .search_iterations
                .unwrap_or(if partial.full { 100_000 } else { 2_000 });
        let haystack_bytes =
            partial
                .haystack_bytes
                .unwrap_or(if partial.full { 65_536 } else { 4_096 });
        if compile_iterations == 0 {
            return Err("--compile-iterations must be greater than zero".to_owned());
        }
        if search_iterations == 0 {
            return Err("--iterations must be greater than zero".to_owned());
        }
        if haystack_bytes < 512 {
            return Err("--haystack-bytes must be at least 512".to_owned());
        }
        let (mut target, target_name) = partial.target.map_or_else(host_target, Ok)?;
        if let Some(features) = partial.features {
            target = target
                .with_features(features)
                .map_err(|error| format!("invalid target feature set: {error}"))?;
        }
        if partial.native_enabled
            && partial.native_run
            && !target_is_host(target)
            && partial.emit_native.is_none()
        {
            return Err(
                "a cross-target native run needs --emit-native DIR; add --no-native-run to make \
                 the non-execution intent explicit"
                    .to_owned(),
            );
        }
        Ok(Some(Self {
            compile_iterations,
            search_iterations,
            haystack_bytes,
            target,
            target_name,
            emit_native: partial.emit_native,
            native_enabled: partial.native_enabled,
            native_run: partial.native_run && target_is_host(target),
        }))
    }
}

fn next_os(arguments: &mut impl Iterator<Item = OsString>, flag: &str) -> Result<OsString, String> {
    arguments
        .next()
        .ok_or_else(|| format!("{flag} requires a value"))
}

fn next_utf8(arguments: &mut impl Iterator<Item = OsString>, flag: &str) -> Result<String, String> {
    next_os(arguments, flag)?
        .into_string()
        .map_err(|_| format!("{flag} requires a UTF-8 value"))
}

fn parse_next<T>(arguments: &mut impl Iterator<Item = OsString>, flag: &str) -> Result<T, String>
where
    T: std::str::FromStr,
{
    next_utf8(arguments, flag)?
        .parse()
        .map_err(|_| format!("{flag} requires a valid integer"))
}

fn parse_target(value: &str) -> Result<(Target, &'static str), String> {
    match value {
        "linux-x86_64" => Ok((Target::x86_64_linux(), "linux-x86_64")),
        "linux-aarch64" => Ok((Target::aarch64_linux(), "linux-aarch64")),
        "macos-x86_64" => Ok((Target::x86_64_macos(), "macos-x86_64")),
        "macos-aarch64" => Ok((Target::aarch64_macos(), "macos-aarch64")),
        _ => Err(format!("unsupported target {value:?}\n\n{}", usage())),
    }
}

fn parse_features(value: &str) -> Result<FeatureSet, String> {
    if value.is_empty() || value == "none" {
        return Ok(FeatureSet::EMPTY);
    }
    let mut features = FeatureSet::EMPTY;
    for name in value.split(',') {
        let feature = match name {
            "sse2" => CpuFeature::X86Sse2,
            "avx2" => CpuFeature::X86Avx2,
            "avx512f" => CpuFeature::X86Avx512F,
            "avx512bw" => CpuFeature::X86Avx512Bw,
            "avx512vl" => CpuFeature::X86Avx512Vl,
            "asimd" => CpuFeature::Aarch64Asimd,
            "sve" => CpuFeature::Aarch64Sve,
            "sve2" => CpuFeature::Aarch64Sve2,
            _ => return Err(format!("unknown CPU feature {name:?}\n\n{}", usage())),
        };
        features = features.with(feature);
    }
    Ok(features)
}

fn host_target() -> Result<(Target, &'static str), String> {
    if cfg!(all(target_os = "linux", target_arch = "x86_64")) {
        Ok((Target::x86_64_linux(), "linux-x86_64"))
    } else if cfg!(all(target_os = "linux", target_arch = "aarch64")) {
        Ok((Target::aarch64_linux(), "linux-aarch64"))
    } else if cfg!(all(target_os = "macos", target_arch = "x86_64")) {
        Ok((Target::x86_64_macos(), "macos-x86_64"))
    } else if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        Ok((Target::aarch64_macos(), "macos-aarch64"))
    } else {
        Err(
            "the native benchmark host must be x86-64/AArch64 Linux/macOS; use --target with \
             --no-native-run for object generation"
                .to_owned(),
        )
    }
}

fn target_is_host(target: Target) -> bool {
    let architecture_matches = match target.architecture {
        Architecture::X86_64 => cfg!(target_arch = "x86_64"),
        Architecture::Aarch64 => cfg!(target_arch = "aarch64"),
    };
    let operating_system_matches = match target.operating_system {
        OperatingSystem::Linux => cfg!(target_os = "linux"),
        OperatingSystem::Macos => cfg!(target_os = "macos"),
    };
    architecture_matches && operating_system_matches
}

#[derive(Debug)]
struct Generator {
    state: u64,
}

impl Generator {
    const fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next(&mut self) -> u64 {
        let mut value = self.state;
        value ^= value << 13;
        value ^= value >> 7;
        value ^= value << 17;
        self.state = value;
        value
    }

    fn bounded(&mut self, bound: usize) -> usize {
        let bound_u64 = u64::try_from(bound).expect("benchmark dimensions fit u64");
        usize::try_from(self.next() % bound_u64).expect("generated index fits usize")
    }

    fn token(&mut self, length: usize) -> String {
        const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyz";
        let mut token = String::with_capacity(length);
        for _ in 0..length {
            token.push(char::from(ALPHABET[self.bounded(ALPHABET.len())]));
        }
        token
    }
}

#[derive(Clone, Debug)]
struct CaseSpec {
    name: &'static str,
    stratum: &'static str,
    pattern: String,
    fixture: Vec<u8>,
    frame: Frame,
    output: OutputContract,
}

#[derive(Clone, Copy, Debug)]
enum Frame {
    Plain,
    Line,
}

#[derive(Debug)]
struct GeneratedCase {
    name: &'static str,
    stratum: &'static str,
    pattern: String,
    haystack: Vec<u8>,
    window: SearchWindow,
    output: OutputContract,
}

fn case_specs() -> Vec<CaseSpec> {
    let mut generator = Generator::new(0x6672_652d_616f_7421);
    let literal = generator.token(9);
    let concat_left = generator.token(3);
    let concat_right = generator.token(4);
    let alternatives = [generator.token(5), generator.token(7), generator.token(9)];
    let greedy_long = generator.token(2);
    let greedy_short = generator.token(1);
    let lazy_long = generator.token(2);
    let lazy_short = generator.token(1);
    let nullable_long = generator.token(2);
    let nullable_short = generator.token(1);
    let unicode_suffix = generator.token(2);
    let line_prefix = generator.token(3);
    let word_left = generator.token(5);
    let word_right = generator.token(6);

    vec![
        CaseSpec {
            name: "literal_00",
            stratum: "literal",
            pattern: literal.clone(),
            fixture: literal.into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "class_00",
            stratum: "class",
            pattern: "[A-F0-9_]{5,11}".to_owned(),
            fixture: b"A9_F0".to_vec(),
            frame: Frame::Plain,
            output: OutputContract::Exists,
        },
        CaseSpec {
            name: "concat_00",
            stratum: "concat",
            pattern: format!("{concat_left}[0-9]{{2}}{concat_right}"),
            fixture: format!("{concat_left}42{concat_right}").into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::SelectedEnd,
        },
        CaseSpec {
            name: "alternation_00",
            stratum: "alternation",
            pattern: format!(
                "(?:{}|{}|{})",
                alternatives[0], alternatives[1], alternatives[2]
            ),
            fixture: alternatives[1].as_bytes().to_vec(),
            frame: Frame::Plain,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "greedy_repeat_00",
            stratum: "greedy_repeat",
            pattern: format!("(?:{greedy_long}|{greedy_short}){{2,7}}"),
            fixture: format!("{greedy_long}{greedy_short}{greedy_long}{greedy_short}").into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "lazy_repeat_00",
            stratum: "lazy_repeat",
            pattern: format!("(?:{lazy_long}|{lazy_short}){{2,7}}?"),
            fixture: format!("{lazy_long}{lazy_short}{lazy_long}{lazy_short}").into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "nullable_00",
            stratum: "nullable",
            pattern: format!("(?:{nullable_long}|{nullable_short})*"),
            fixture: format!("{nullable_long}{nullable_short}").into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::SelectedEnd,
        },
        CaseSpec {
            name: "unicode_00",
            stratum: "unicode",
            pattern: format!("(?:Δ{unicode_suffix}|東京{unicode_suffix}|é{unicode_suffix}){{1,3}}"),
            fixture: format!("東京{unicode_suffix}Δ{unicode_suffix}").into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "assertion_line_00",
            stratum: "assertion",
            pattern: format!(r"(?m)^{line_prefix}[A-Za-z0-9_]{{2,8}}$"),
            fixture: format!("{line_prefix}42").into_bytes(),
            frame: Frame::Line,
            output: OutputContract::Span,
        },
        CaseSpec {
            name: "assertion_word_00",
            stratum: "assertion",
            pattern: format!(r"(?-u:\b(?:{word_left}|{word_right})\b)"),
            fixture: word_right.into_bytes(),
            frame: Frame::Plain,
            output: OutputContract::Exists,
        },
    ]
}

fn generate_cases(haystack_bytes: usize) -> Vec<GeneratedCase> {
    const BACKGROUND: &[u8] = b"!#$%&()*+,-./:;<=>?@[]^_{|}~";
    let mut generator = Generator::new(0x6765_6e65_7261_7465);
    case_specs()
        .into_iter()
        .map(|spec| {
            let mut haystack = Vec::with_capacity(haystack_bytes);
            haystack.resize_with(haystack_bytes, || {
                BACKGROUND[generator.bounded(BACKGROUND.len())]
            });
            let window_start = 8 + generator.bounded(31);
            let window_end = haystack_bytes - 8 - generator.bounded(31);
            let framed = match spec.frame {
                Frame::Plain => spec.fixture,
                Frame::Line => {
                    let mut bytes = Vec::with_capacity(spec.fixture.len() + 2);
                    bytes.push(b'\n');
                    bytes.extend_from_slice(&spec.fixture);
                    bytes.push(b'\n');
                    bytes
                }
            };
            let available = window_end - window_start - framed.len() - 128;
            let position = window_start + 64 + generator.bounded(available);
            haystack[position..position + framed.len()].copy_from_slice(&framed);
            GeneratedCase {
                name: spec.name,
                stratum: spec.stratum,
                pattern: spec.pattern,
                haystack,
                window: SearchWindow::new(window_start, window_end),
                output: spec.output,
            }
        })
        .collect()
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct AbiResult {
    status: u32,
    start: usize,
    end: usize,
}

impl AbiResult {
    fn from_match(result: MatchResult) -> Self {
        match result {
            MatchResult::Exists(found) => Self {
                status: u32::from(found),
                start: 0,
                end: 0,
            },
            MatchResult::SelectedEnd(Some(end)) => Self {
                status: 1,
                start: end,
                end,
            },
            MatchResult::SelectedEnd(None) | MatchResult::Span(None) => Self {
                status: 0,
                start: 0,
                end: 0,
            },
            MatchResult::Span(Some((start, end))) => Self {
                status: 1,
                start,
                end,
            },
        }
    }
}

fn checksum_step(checksum: u64, result: AbiResult, iteration: u64) -> u64 {
    let start = u64::try_from(result.start).expect("supported targets use at most 64-bit size_t");
    let end = u64::try_from(result.end).expect("supported targets use at most 64-bit size_t");
    let value = u64::from(result.status)
        .wrapping_add(1)
        .wrapping_mul(CHECKSUM_MIX)
        ^ start.wrapping_add(START_MIX).rotate_left(17)
        ^ end.wrapping_add(END_MIX).rotate_left(41);
    checksum.rotate_left(7) ^ value ^ iteration.wrapping_mul(ITERATION_MIX)
}

#[derive(Debug)]
struct Measurement {
    compiled: CompiledRegex,
    compile_ns: u128,
    search_ns: u128,
    expected: AbiResult,
    checksum: u64,
}

fn measure(
    case: &GeneratedCase,
    config: &Config,
    mode: CompileMode,
) -> Result<Measurement, String> {
    let compile_start = Instant::now();
    let mut compiled = None;
    for _ in 0..config.compile_iterations {
        let artifact = compile(
            CompileRequest::new(case.pattern.clone(), config.target)
                .mode(mode)
                .output(case.output),
        )
        .map_err(|error| format!("{} {mode:?} compilation failed: {error}", case.name))?;
        black_box(artifact.object().len());
        compiled = Some(artifact);
    }
    let compile_ns = compile_start.elapsed().as_nanos();
    let compiled = compiled.ok_or_else(|| "compile iteration count was zero".to_owned())?;
    let mut workspace = compiled
        .program()
        .prepare_workspace()
        .map_err(|error| format!("{} workspace preparation failed: {error}", case.name))?;
    let expected_match = compiled
        .program()
        .search_with_workspace(&case.haystack, case.window, &mut workspace)
        .map_err(|error| format!("{} untimed portable search failed: {error}", case.name))?;
    let expected = AbiResult::from_match(expected_match);
    let mut checksum = 0_u64;
    let search_start = Instant::now();
    for iteration in 0..config.search_iterations {
        let found = compiled
            .program()
            .search_with_workspace(black_box(&case.haystack), case.window, &mut workspace)
            .map_err(|error| format!("{} portable search failed: {error}", case.name))?;
        let result = AbiResult::from_match(found);
        if result != expected {
            return Err(format!(
                "{} portable result changed during steady-state execution",
                case.name
            ));
        }
        checksum = checksum_step(checksum, result, iteration);
    }
    let search_ns = search_start.elapsed().as_nanos();
    black_box(checksum);
    Ok(Measurement {
        compiled,
        compile_ns,
        search_ns,
        expected,
        checksum,
    })
}

fn mode_name(mode: CompileMode) -> &'static str {
    match mode {
        CompileMode::Fast => "fast",
        CompileMode::Optimizing => "optimizing",
    }
}

fn output_name(output: OutputContract) -> &'static str {
    match output {
        OutputContract::Exists => "exists",
        OutputContract::SelectedEnd => "selected_end",
        OutputContract::Span => "span",
    }
}

fn engine_name(engine: EngineKind) -> &'static str {
    match engine {
        EngineKind::OrderedNfa => "ordered_nfa",
        EngineKind::OrderedDfa => "ordered_dfa",
        EngineKind::OrderedContextDfa => "ordered_context_dfa",
    }
}

fn start_accelerator_name(accelerator: StartAccelerator) -> &'static str {
    match accelerator {
        StartAccelerator::None => "none",
        StartAccelerator::Scalar => "scalar",
        StartAccelerator::X86Sse2 => "x86_sse2",
        StartAccelerator::X86Avx2 => "x86_avx2",
        StartAccelerator::X86Avx512Bw => "x86_avx512bw",
        StartAccelerator::Aarch64Asimd => "aarch64_asimd",
        StartAccelerator::Aarch64Sve => "aarch64_sve",
        StartAccelerator::Aarch64Sve2 => "aarch64_sve2",
    }
}

fn engine_selection_reason_name(reason: EngineSelectionReason) -> &'static str {
    match reason {
        EngineSelectionReason::FastMode => "fast_mode",
        EngineSelectionReason::CompleteDfa => "complete_dfa",
        EngineSelectionReason::CompleteContextDfa => "complete_context_dfa",
        EngineSelectionReason::ContextAssertions => "context_assertions",
        EngineSelectionReason::DeterminizationResourceLimit => "determinization_resource_limit",
    }
}

fn optional_usize(value: Option<usize>) -> String {
    value.map_or_else(|| "-".to_owned(), |number| number.to_string())
}

fn optional_u64(value: Option<u64>) -> String {
    value.map_or_else(|| "-".to_owned(), |number| number.to_string())
}

fn emit_portable_row(
    case: &GeneratedCase,
    config: &Config,
    mode: CompileMode,
    measurement: &Measurement,
) {
    let receipt = measurement.compiled.receipt();
    let dfa = receipt.dfa;
    let prefix = receipt.anchored_prefix;
    let transitions = dfa.map(fre_aot_regex::DfaStats::transitions);
    let compile_per_iteration = measurement.compile_ns / u128::from(config.compile_iterations);
    let search_per_iteration = measurement.search_ns / u128::from(config.search_iterations);
    println!(
        "compile_portable\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\tok",
        case.name,
        case.stratum,
        case.pattern,
        config.target_name,
        config.target.features.bits(),
        mode_name(mode),
        output_name(case.output),
        engine_name(receipt.engine),
        engine_selection_reason_name(receipt.engine_selection_reason),
        start_accelerator_name(receipt.start_accelerator),
        prefix.guaranteed_bytes,
        prefix.selective_positions,
        receipt.anchored_prefix_filter_bytes,
        prefix.derivation_work,
        prefix.resource_limited,
        prefix.context_assertions,
        config.compile_iterations,
        measurement.compile_ns,
        compile_per_iteration,
        receipt.thompson_states,
        receipt.thompson_edges,
        optional_usize(dfa.map(|stats| stats.boundary_classes)),
        optional_usize(dfa.map(|stats| stats.alphabet_classes)),
        optional_usize(dfa.map(|stats| stats.forward_states)),
        optional_usize(dfa.map(|stats| stats.reverse_states)),
        optional_usize(transitions),
        optional_u64(dfa.map(|stats| stats.build_work)),
        receipt.program_bytes,
        receipt.code_bytes,
        receipt.data_bytes,
        receipt.object_bytes,
        case.haystack.len(),
        case.window.start(),
        case.window.end(),
        config.search_iterations,
        measurement.search_ns,
        search_per_iteration,
        measurement.checksum,
    );
}

#[derive(Debug)]
struct NativeCase {
    name: &'static str,
    stratum: &'static str,
    pattern: String,
    output: OutputContract,
    haystack: Vec<u8>,
    window: SearchWindow,
    object: Vec<u8>,
    symbol: String,
    expected: AbiResult,
    portable_checksum: u64,
}

impl NativeCase {
    fn from_measurement(case: &GeneratedCase, measurement: &Measurement) -> Self {
        Self {
            name: case.name,
            stratum: case.stratum,
            pattern: case.pattern.clone(),
            output: case.output,
            haystack: case.haystack.clone(),
            window: case.window,
            object: measurement.compiled.object().to_vec(),
            symbol: measurement.compiled.module().entry_symbol().to_owned(),
            expected: measurement.expected,
            portable_checksum: measurement.checksum,
        }
    }
}

fn c_bytes(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(u8::to_string)
        .collect::<Vec<_>>()
        .join(",")
}

fn c_string(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            character if character.is_ascii_graphic() || character == ' ' => {
                escaped.push(character);
            }
            character => {
                for byte in character.to_string().bytes() {
                    write!(&mut escaped, "\\x{byte:02x}").expect("writing to a String cannot fail");
                }
            }
        }
    }
    escaped
}

fn build_c_harness(cases: &[NativeCase], target_name: &str, default_iterations: u64) -> String {
    let mut source = String::from(
        "#define _POSIX_C_SOURCE 200809L\n\
         #include <errno.h>\n\
         #include <inttypes.h>\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\
         #include <stdio.h>\n\
         #include <stdlib.h>\n\
         #include <time.h>\n\n\
         static uint64_t rotate_left(uint64_t value, unsigned count) {\n\
           return (value << count) | (value >> (64U - count));\n\
         }\n\
         static uint64_t now_ns(void) {\n\
           struct timespec value;\n\
           if (clock_gettime(CLOCK_MONOTONIC, &value) != 0) return 0;\n\
           return (uint64_t)value.tv_sec * UINT64_C(1000000000) + (uint64_t)value.tv_nsec;\n\
         }\n\
         static uint64_t checksum_step(uint64_t checksum, uint32_t status,\n\
                                       size_t start, size_t end, uint64_t iteration) {\n\
           uint64_t value = ((uint64_t)status + UINT64_C(1)) * UINT64_C(0x9e3779b97f4a7c15);\n\
           value ^= rotate_left((uint64_t)start + UINT64_C(0xd1b54a32d192ed03), 17U);\n\
           value ^= rotate_left((uint64_t)end + UINT64_C(0x94d049bb133111eb), 41U);\n\
           return rotate_left(checksum, 7U) ^ value ^\n\
                  iteration * UINT64_C(0xbf58476d1ce4e5b9);\n\
         }\n\n",
    );
    for (index, case) in cases.iter().enumerate() {
        writeln!(
            &mut source,
            "extern uint32_t {}(const unsigned char *, size_t, size_t, size_t, size_t *);",
            case.symbol
        )
        .expect("writing to a String cannot fail");
        writeln!(
            &mut source,
            "static const unsigned char haystack_{index}[] = {{{}}};",
            c_bytes(&case.haystack)
        )
        .expect("writing to a String cannot fail");
    }
    writeln!(
        &mut source,
        "\nint main(int argc, char **argv) {{\n\
         uint64_t iterations = UINT64_C({default_iterations});\n\
         if (argc > 2) {{ fprintf(stderr, \"usage: %s [ITERATIONS]\\n\", argv[0]); return 2; }}\n\
         if (argc == 2) {{\n\
           char *end = NULL; errno = 0;\n\
           unsigned long long parsed = strtoull(argv[1], &end, 10);\n\
           if (errno != 0 || end == argv[1] || *end != '\\0' || parsed == 0) {{\n\
             fprintf(stderr, \"ITERATIONS must be a positive integer\\n\"); return 2;\n\
           }}\n\
           iterations = (uint64_t)parsed;\n\
         }}\n\
         puts(\"#native\\tcase\\tstratum\\ttarget\\titerations\\telapsed_ns\\tns_per_iteration\\tchecksum\\tstatus\");"
    )
    .expect("writing to a String cannot fail");
    for (index, case) in cases.iter().enumerate() {
        let failure = 10 + index;
        writeln!(
            &mut source,
            "  {{\n\
               size_t result[2] = {{ SIZE_MAX, SIZE_MAX }};\n\
               uint32_t status = {symbol}(haystack_{index}, sizeof(haystack_{index}), {start}, {end}, result);\n\
               if (status != {expected_status} || result[0] != {expected_start} || result[1] != {expected_end}) {{\n\
                 fprintf(stderr, \"native semantic check failed for {name}: got %u/%zu/%zu\\n\",\n\
                         status, result[0], result[1]); return {failure};\n\
               }}\n\
               uint64_t expected_checksum = 0;\n\
               for (uint64_t iteration = 0; iteration < iterations; ++iteration) {{\n\
                 expected_checksum = checksum_step(expected_checksum, {expected_status},\n\
                                                   {expected_start}, {expected_end}, iteration);\n\
               }}\n\
               uint64_t checksum = 0;\n\
               uint64_t before = now_ns();\n\
               for (uint64_t iteration = 0; iteration < iterations; ++iteration) {{\n\
                 status = {symbol}(haystack_{index}, sizeof(haystack_{index}), {start}, {end}, result);\n\
                 checksum = checksum_step(checksum, status, result[0], result[1], iteration);\n\
               }}\n\
               uint64_t elapsed = now_ns() - before;\n\
               if (checksum != expected_checksum) {{\n\
                 fprintf(stderr, \"native timed checksum failed for {name}\\n\"); return {failure};\n\
               }}\n\
               printf(\"native\\t{name}\\t{stratum}\\t{target}\\t%\" PRIu64 \"\\t%\" PRIu64\n\
                      \"\\t%\" PRIu64 \"\\t%\" PRIu64 \"\\tok\\n\",\n\
                      iterations, elapsed, elapsed / iterations, checksum);\n\
             }}",
            symbol = case.symbol,
            start = case.window.start(),
            end = case.window.end(),
            expected_status = case.expected.status,
            expected_start = case.expected.start,
            expected_end = case.expected.end,
            name = c_string(case.name),
            stratum = c_string(case.stratum),
            target = c_string(target_name),
        )
        .expect("writing to a String cannot fail");
    }
    source.push_str("  return 0;\n}\n");
    source
}

fn create_new_directory(path: &Path) -> Result<(), String> {
    fs::create_dir(path).map_err(|error| {
        format!(
            "could not create new native bundle directory {}: {error}",
            path.display()
        )
    })
}

fn temporary_directory() -> Result<PathBuf, String> {
    let root = env::temp_dir();
    for suffix in 0_u32..100 {
        let candidate = root.join(format!(
            "fre-generated-aot-native-{}-{suffix}",
            std::process::id()
        ));
        match fs::create_dir(&candidate) {
            Ok(()) => return Ok(candidate),
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
            Err(error) => {
                return Err(format!(
                    "could not create temporary native directory {}: {error}",
                    candidate.display()
                ));
            }
        }
    }
    Err("could not allocate a unique temporary native directory".to_owned())
}

fn write_bundle(
    directory: &Path,
    cases: &[NativeCase],
    config: &Config,
    create: bool,
) -> Result<Vec<PathBuf>, String> {
    if create {
        create_new_directory(directory)?;
    }
    let harness = build_c_harness(cases, config.target_name, config.search_iterations);
    fs::write(directory.join("harness.c"), harness)
        .map_err(|error| format!("could not write native C harness: {error}"))?;

    let mut manifest = String::from(
        "#case\tstratum\tpattern\toutput\tobject\tentry_symbol\thaystack_bytes\twindow_start\twindow_end\texpected_status\texpected_start\texpected_end\tportable_checksum_at_default_iterations\n",
    );
    let mut object_paths = Vec::with_capacity(cases.len());
    for (index, case) in cases.iter().enumerate() {
        let object_name = format!("case_{index:03}.o");
        let object_path = directory.join(&object_name);
        fs::write(&object_path, &case.object)
            .map_err(|error| format!("could not write {}: {error}", object_path.display()))?;
        object_paths.push(object_path);
        writeln!(
            &mut manifest,
            "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}",
            case.name,
            case.stratum,
            case.pattern,
            output_name(case.output),
            object_name,
            case.symbol,
            case.haystack.len(),
            case.window.start(),
            case.window.end(),
            case.expected.status,
            case.expected.start,
            case.expected.end,
            case.portable_checksum,
        )
        .expect("writing to a String cannot fail");
    }
    fs::write(directory.join("manifest.tsv"), manifest)
        .map_err(|error| format!("could not write native manifest: {error}"))?;
    let object_arguments = (0..cases.len())
        .map(|index| format!("case_{index:03}.o"))
        .collect::<Vec<_>>()
        .join(" ");
    let script = format!(
        "#!/bin/sh\n\
         set -eu\n\
         compiler=\"${{CC:-cc}}\"\n\
         \"$compiler\" -O3 -std=c11 harness.c {object_arguments} -o native-benchmark\n\
         exec ./native-benchmark \"${{1:-{}}}\"\n",
        config.search_iterations
    );
    fs::write(directory.join("run.sh"), script)
        .map_err(|error| format!("could not write native run script: {error}"))?;
    let readme = format!(
        "FRE deterministic generated native AOT benchmark bundle\n\
         target: {}\n\
         required feature bits: {:#x}\n\
         cases: {}\n\n\
         This bundle contains generated structural cases only. It reads no external corpus.\n\
         Run only on a CPU/OS context providing the required feature bits. Build and run on\n\
         the named target with:\n\n\
           sh run.sh [ITERATIONS]\n\n\
         CC may name an alternative C compiler executable. The harness validates every\n\
         native status/start/end result before timing and checks the timed aggregate afterward.\n\
         It exits nonzero on a mismatch. manifest.tsv records portable expected values and\n\
         the checksum for the bundle's default iteration count.\n",
        config.target_name,
        config.target.features.bits(),
        cases.len(),
    );
    fs::write(directory.join("README.txt"), readme)
        .map_err(|error| format!("could not write native README: {error}"))?;
    Ok(object_paths)
}

fn compile_harness(directory: &Path, object_paths: &[PathBuf]) -> Result<PathBuf, String> {
    let executable = directory.join("native-benchmark");
    let configured = env::var_os("CC");
    let compiler = configured.clone().unwrap_or_else(|| OsString::from("cc"));
    let mut command = Command::new(&compiler);
    command
        .arg("-O3")
        .arg("-std=c11")
        .arg(directory.join("harness.c"))
        .args(object_paths)
        .arg("-o")
        .arg(&executable);
    let output = match command.output() {
        Ok(output) => output,
        Err(error) if configured.is_none() => Command::new("clang")
            .arg("-O3")
            .arg("-std=c11")
            .arg(directory.join("harness.c"))
            .args(object_paths)
            .arg("-o")
            .arg(&executable)
            .output()
            .map_err(|fallback| {
                format!("could not invoke cc ({error}) or clang ({fallback}) for native harness")
            })?,
        Err(error) => {
            return Err(format!(
                "could not invoke C compiler {}: {error}",
                compiler.to_string_lossy()
            ));
        }
    };
    if !output.status.success() {
        return Err(format!(
            "native C harness compilation failed:\n{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(executable)
}

fn execute_and_verify(
    executable: &Path,
    directory: &Path,
    config: &Config,
    cases: &[NativeCase],
) -> Result<(), String> {
    let output = Command::new(executable)
        .arg(config.search_iterations.to_string())
        .current_dir(directory)
        .output()
        .map_err(|error| format!("could not execute native C harness: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "native C harness failed with {}:\n{}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let stdout = String::from_utf8(output.stdout)
        .map_err(|error| format!("native harness emitted non-UTF-8 output: {error}"))?;
    let expected = cases
        .iter()
        .map(|case| (case.name, case.portable_checksum))
        .collect::<BTreeMap<_, _>>();
    let mut observed = BTreeMap::new();
    for line in stdout.lines() {
        if line.starts_with('#') {
            println!("{line}");
            continue;
        }
        let columns = line.split('\t').collect::<Vec<_>>();
        if columns.len() != 9 || columns[0] != "native" || columns[8] != "ok" {
            return Err(format!("malformed native harness row: {line}"));
        }
        let iterations = columns[4]
            .parse::<u64>()
            .map_err(|_| format!("invalid native iteration count in: {line}"))?;
        if iterations != config.search_iterations {
            return Err(format!("native iteration count mismatch in: {line}"));
        }
        let checksum = columns[7]
            .parse::<u64>()
            .map_err(|_| format!("invalid native checksum in: {line}"))?;
        let portable = expected
            .get(columns[1])
            .ok_or_else(|| format!("unknown native case in: {line}"))?;
        if checksum != *portable {
            return Err(format!(
                "native checksum mismatch for {}: native {checksum}, portable {portable}",
                columns[1]
            ));
        }
        if observed.insert(columns[1], checksum).is_some() {
            return Err(format!("duplicate native row for {}", columns[1]));
        }
        println!("{line}");
    }
    if observed.len() != expected.len() {
        return Err(format!(
            "native harness returned {} case rows, expected {}",
            observed.len(),
            expected.len()
        ));
    }
    Ok(())
}

fn clean_temporary_bundle(directory: &Path, object_paths: &[PathBuf]) {
    for file in [
        directory.join("harness.c"),
        directory.join("manifest.tsv"),
        directory.join("run.sh"),
        directory.join("README.txt"),
        directory.join("native-benchmark"),
    ] {
        let _ = fs::remove_file(file);
    }
    for object in object_paths {
        let _ = fs::remove_file(object);
    }
    let _ = fs::remove_dir(directory);
}

fn run(config: &Config) -> Result<(), String> {
    println!(
        "#compile_portable\tcase\tstratum\tpattern\ttarget\tfeature_bits\tmode\toutput\tengine\tengine_selection_reason\tstart_accelerator\tanchored_prefix_bytes\tanchored_prefix_selective_positions\tanchored_prefix_filter_bytes\tanchored_prefix_derivation_work\tanchored_prefix_resource_limited\tanchored_prefix_context_assertions\tcompile_iterations\tcompile_ns\tcompile_ns_per_iteration\tthompson_states\tthompson_edges\tboundary_classes\talphabet_classes\tforward_states\treverse_states\tdfa_transitions\tbuild_work\tprogram_bytes\tcode_bytes\tdata_bytes\tobject_bytes\thaystack_bytes\twindow_start\twindow_end\tsearch_iterations\tsearch_ns\tsearch_ns_per_iteration\tchecksum\tstatus"
    );
    let cases = generate_cases(config.haystack_bytes);
    let mut native_cases = Vec::new();
    for case in &cases {
        for mode in [CompileMode::Fast, CompileMode::Optimizing] {
            let measurement = measure(case, config, mode)?;
            emit_portable_row(case, config, mode, &measurement);
            if config.native_enabled
                && mode == CompileMode::Optimizing
                && measurement.compiled.receipt().engine == EngineKind::OrderedDfa
            {
                native_cases.push(NativeCase::from_measurement(case, &measurement));
            }
        }
    }
    if !config.native_enabled {
        return Ok(());
    }
    if native_cases.is_empty() {
        return Err("no optimizing DFA cases were available for the native bundle".to_owned());
    }

    let persistent = config.emit_native.is_some();
    let directory = if let Some(path) = &config.emit_native {
        path.clone()
    } else {
        temporary_directory()?
    };
    let object_paths = write_bundle(&directory, &native_cases, config, persistent)?;
    eprintln!(
        "generated {} native DFA cases for {} in {}",
        native_cases.len(),
        config.target_name,
        directory.display()
    );
    if config.native_run {
        let executable = compile_harness(&directory, &object_paths)?;
        execute_and_verify(&executable, &directory, config, &native_cases)?;
    } else {
        eprintln!(
            "native execution skipped; transfer {} to a {} host and run `sh run.sh [ITERATIONS]`",
            directory.display(),
            config.target_name
        );
    }
    if !persistent {
        clean_temporary_bundle(&directory, &object_paths);
    }
    Ok(())
}

fn main() -> ExitCode {
    match Config::parse() {
        Ok(None) => {
            println!("{}", usage());
            ExitCode::SUCCESS
        }
        Ok(Some(config)) => match run(&config) {
            Ok(()) => ExitCode::SUCCESS,
            Err(error) => {
                eprintln!("error: {error}");
                ExitCode::FAILURE
            }
        },
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

//! Deterministic, generated evidence for the general AOT compiler.
//!
//! This example deliberately generates its own structural regex inventory and
//! haystacks. It has no corpus input and is suitable for compiler-development
//! measurements without consulting any external benchmark workload.

#![allow(
    clippy::arithmetic_side_effects,
    clippy::too_many_lines,
    reason = "the benchmark uses wrapping checksums and keeps the generated bundle format together"
)]


const CHECKSUM_MIX: u64 = 0x9e37_79b9_7f4a_7c15;
const START_MIX: u64 = 0xd1b5_4a32_d192_ed03;
const END_MIX: u64 = 0x94d0_49bb_1331_11eb;
const ITERATION_MIX: u64 = 0xbf58_476d_1ce4_e5b9;


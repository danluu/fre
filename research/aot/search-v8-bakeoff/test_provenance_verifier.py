def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def table(header: list[str], rows: list[list[str]]) -> bytes:
    return (
        "\n".join(["\t".join(header), *("\t".join(row) for row in rows)]) + "\n"
    ).encode("ascii")


def cargo_lock(
    checksum: str,
    *,
    include_registry: bool = True,
    version: str = "4",
) -> bytes:
    registry = (
        f"""

[[package]]
name = "sha2"
version = "0.10.9"
source = "{CRATES_IO_SOURCE}"
checksum = "{checksum}"
"""
        if include_registry
        else ""
    )
    return f"""# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = {version}

[[package]]
name = "{SEARCH_ROOT_NAME}"
version = "{SEARCH_ROOT_VERSION}"
dependencies = [
 "sha2",
]
{registry}""".encode("ascii")



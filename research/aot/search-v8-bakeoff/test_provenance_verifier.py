    def copied_bundle(self, name: str) -> Path:
        destination = self.root / name
        shutil.copytree(self.bundle, destination)
        return destination

    @staticmethod
    def replace(path: Path, old: str, new: str) -> None:
        path.chmod(0o600)
        text = path.read_text(encoding="ascii")
        if old not in text:
            raise AssertionError(f"missing fixture token {old!r}")
        path.write_text(text.replace(old, new, 1), encoding="ascii")
        path.chmod(0o400)


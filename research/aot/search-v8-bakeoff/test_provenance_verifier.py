    def source_bytes_for_lock(
        self, lock_bytes: bytes, lock_path: str = SEARCH_LOCK_PATH
    ) -> bytes:
        rows = [
            [
                "1",
                "100644",
                "3" * 40,
                str(len(lock_bytes)),
                digest(lock_bytes),
                lock_path,
            ],
            [
                "2",
                "100644",
                "4" * 40,
                "12",
                "5" * 64,
                SEARCH_ROOT_MANIFEST_ROLE.removeprefix("repo:"),
            ],
        ]
        rows.sort(key=lambda row: row[-1].encode("ascii"))
        return table(
            SOURCE_HEADER,
            [[str(index), *row[1:]] for index, row in enumerate(rows, 1)],
        )

    def dependency_bytes(
        self,
        *,
        root_source: str = SEARCH_ROOT_SOURCE,
        root_manifest: str = SEARCH_ROOT_MANIFEST_ROLE,
        registry_checksum: str | None = None,
    ) -> bytes:
        checksum = registry_checksum or self.checksum
        root_key = package_key(SEARCH_ROOT_NAME, SEARCH_ROOT_VERSION, root_source)
        rows = [
            [
                root_key,
                SEARCH_ROOT_NAME,
                SEARCH_ROOT_VERSION,
                "path",
                root_source,
                root_manifest,
                self.tree,
                "none",
                "bin,custom-build",
                "none",
                f"sha2|build|all|{self.registry_key}",
            ],
            [
                self.registry_key,
                "sha2",
                "0.10.9",
                "registry",
                CRATES_IO_SOURCE,
                registry_manifest_role(self.registry_key),
                "none",
                checksum,
                "lib",
                "default",
                "none",
            ],
        ]
        rows.sort(key=lambda row: row[0])
        return table(
            DEPENDENCY_HEADER,
            [[str(index), *row] for index, row in enumerate(rows, 1)],
        )

    def archive_manifest_bytes(
        self,
        *,
        checksum: str | None = None,
        role: str | None = None,
    ) -> bytes:
        checksum = checksum or self.checksum
        return table(
            ARCHIVE_HEADER,
            [
                [
                    "1",
                    self.registry_key,
                    "sha2",
                    "0.10.9",
                    CRATES_IO_SOURCE,
                    checksum,
                    str(len(self.archive_bytes)),
                    checksum,
                    role or registry_archive_role(self.registry_key),
                ]
            ],
        )


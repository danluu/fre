        def fsync_then_displace(descriptor: int) -> None:
            nonlocal moved
            real_fsync(descriptor)
            info = os.fstat(descriptor)
            if not moved and (info.st_dev, info.st_ino) == parent_identity:
                parent.rename(displaced)
                parent.mkdir(mode=0o700)
                moved = True

        with mock.patch.object(
            provenance_common.os, "fsync", side_effect=fsync_then_displace
        ), self.assertRaisesRegex(
            ProvenanceError,
            "absolute output parent changed before publication",
        ):
            generate_provenance.generate(
                self.generator_options(output=parent / "bundle")
            )
        self.assertTrue(moved)

